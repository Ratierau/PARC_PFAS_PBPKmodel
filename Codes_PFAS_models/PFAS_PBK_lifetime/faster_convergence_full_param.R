                                          ",AFbirth="               ,AFbirth,
                                          ",AKbirth="               ,AKbirth,
                                          ",ALunbirth="             ,ALunbirth,
                                          ",ASkbirth="              ,ASkbirth,
                                          ",ARbirth="               ,ARbirth,
                                          ",Afilbirth="             ,Afilbirth,
                                          ",Adelaybirth="           ,Adelaybirth,
                                          ",Aurinebirth="           ,Aurinebirth,")"))))

  previous.diff<-Inf
  diff<-Inf
  loop<-2
  while(loop<=max.loops&diff>max.diff) {
    y[loop]<-eval(parse(text=paste0(FUN,"("                   ,
                                    "age="                    ,age,
                                    ",BW="                    ,BW,
                                    ",height="                ,height,
                                    ",Gender='"               ,Gender,
                                    "',TSTART="               ,TSTART,
                                    ",TSTOP="                 ,TSTOP,                
                                    ",DT="                    ,DT,                  
                                    ",exposure_duration="     ,exposure_duration,
                                    ",age_start_occ_exp="     ,age_start_occ_exp,
                                    ",age_stop_occ_exp="      ,age_stop_occ_exp,
                                    ",age_start_menstruation=",age_start_menstruation,
                                    ",age_stop_menstruation=" ,age_stop_menstruation,
