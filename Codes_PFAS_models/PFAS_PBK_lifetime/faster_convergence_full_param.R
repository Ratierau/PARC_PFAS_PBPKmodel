                                    ",ffatepi="               ,ffatepi,
                                    ",ffatbl="                ,ffatbl,
                                    ",Kpcell="                ,Kpcell, 
                                    ",Drinkrate="             ,Drinkrate, 
                                    ",MW="                    ,MW,
                                    ",logP="                  ,logP,
