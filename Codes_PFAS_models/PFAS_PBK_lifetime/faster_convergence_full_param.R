                                        Cdermal               =NA,
                                        Tmc                   =NA,
                                        Kt                    =NA,
                                        kurinec               =NA,
                                        CLfaeces              =NA,
                                        Free                  =NA,
                                        PL                    =NA,
                                        PF                    =NA,
                                        PK                    =NA,
