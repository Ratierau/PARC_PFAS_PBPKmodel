                                    ",Kpve="                  ,Kpve,
                                    ",Kpsc="                  ,Kpsc,
                                    ",Oralexpo="              ,x[loop],
                                    ",Drinkconc="             ,Drinkconc,
                                    ",Cinh="                  ,Cinh,
                                    ",Cdermal="               ,Cdermal,
                                    ",Tmc="                   ,Tmc,
                                    ",Kt="                    ,Kt,
                                    ",kurinec="               ,kurinec,
                                    ",CLfaeces="              ,CLfaeces,
                                    ",Free="                  ,Free,
                                    ",PL="                    ,PL,
                                    ",PF="                    ,PF,
                                    ",PK="                    ,PK,
                                    ",PSk="                   ,PSk,
                                    ",PR="                    ,PR,
                                    ",PG="                    ,PG,
