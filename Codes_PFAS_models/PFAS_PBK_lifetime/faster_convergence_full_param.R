  # fixed

  ## Initial value (μg/kg/day)
  x<-y<-numeric(0)
  
  x[1]<-0
  x[2]<-c
  y[1]<-eval(parse(text=parse(text=paste0(FUN,"("                   ,
                                          "age="                    ,age,
                                          ",BW="                    ,BW,
                                          ",height="                ,height,
                                          ",Gender='"               ,Gender,
