                                        AFbirth               =NA,
                                        AKbirth               =NA,
                                        ALunbirth             =NA,
                                        ASkbirth              =NA,
                                        ARbirth               =NA,
                                        Afilbirth             =NA,
                                        Adelaybirth           =NA,
